import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import App from './App.tsx';
import { ErrorBoundary } from './components/ErrorBoundary.tsx';
import './index.css';

if (typeof document !== 'undefined' && typeof window !== 'undefined') {
  const preventEvent = (e: Event) => {
    e.preventDefault();
  };

  // Prevent iOS Safari pinch/gesture zoom
  document.addEventListener('gesturestart', preventEvent, { passive: false });
  document.addEventListener('gesturechange', preventEvent, { passive: false });
  document.addEventListener('gestureend', preventEvent, { passive: false });

  // Prevent multi-finger pinch zoom on mobile browsers
  document.addEventListener(
    'touchstart',
    (e) => {
      if (e.touches.length > 1) {
        e.preventDefault();
      }
    },
    { passive: false }
  );
  document.addEventListener(
    'touchmove',
    (e) => {
      if (e.touches.length > 1) {
        e.preventDefault();
      }
    },
    { passive: false }
  );

  // Prevent trackpad pinch & Ctrl/Cmd + Scroll zoom on desktop
  window.addEventListener(
    'wheel',
    (e) => {
      if (e.ctrlKey || e.metaKey) {
        e.preventDefault();
      }
    },
    { passive: false }
  );

  // Prevent Ctrl/Cmd + (+, -, =, 0) keyboard zoom shortcuts
  window.addEventListener('keydown', (e) => {
    if ((e.ctrlKey || e.metaKey) && ['+', '-', '=', '_', '0'].includes(e.key)) {
      e.preventDefault();
    }
  });
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <ErrorBoundary>
      <App />
    </ErrorBoundary>
  </StrictMode>
);
